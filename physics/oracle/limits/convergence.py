"""Discrete chain against continuous rope: frequencies and mode shapes along the doubling sequence.

The chain is the paper's section-5 system: N equal masses M/N on N rods of length L/N, total
length L and mass M fixed, linearized from first principles (``linearization.py``). The rope is
its continuum limit (74), solved in ``rope.py``. N follows the paper's doubling n_p = n 2^p
from n = 1 up to N = 1024, plus a second sequence from n = 3.

Two references are compared:
* the rope of length L (the paper's limit): errors fall like 1/N;
* the rope of length L (1 + 1/(2N)): errors fall like 1/N^2. The chain's equation (66) is the
  standard second-order conservative discretization of that slightly longer rope (the tension
  of rod j, (n - j + 1) m g, is the rope tension at the rod's upper end, which is the longer
  rope's tension at the rod's midpoint), which explains the 1/N law and its constant:
  omega_N / omega = (1 + 1/(2N))^(-1/2) + O(N^-2) = 1 - 1/(4N) + O(N^-2) for each fixed mode.
  The O(N^-2) term grows with the square of the mode number, so at a given N only the modes
  below about 1.6 sqrt(N) are slower than the rope's; the higher ones are faster.

Run from physics/oracle:  uv run --no-sync python limits/convergence.py
Writes limits/convergence.md next to this file.
"""

import itertools
import math
from pathlib import Path

import numpy as np
from linearization import normal_frequencies_theta, normal_modes, uniform_chain
from rope import frequencies_np, normalized_modes_np
from scipy.special import jn_zeros

# Any positive values do: every reported quantity is a dimensionless ratio. Non-unit values
# keep a scale error from hiding.
G = 9.81
LENGTH = 2.0
MASS = 3.0
MODES = 3


def chain_level(count, modes=MODES, g=G, length=LENGTH, mass=MASS):
    """Frequencies and normalized x-mode shapes of the N = count chain."""
    masses, lengths = uniform_chain(mass, length, count)
    omega, vectors = normal_modes(masses, lengths, g, modes)
    shapes = []
    for column in range(vectors.shape[1]):
        v = vectors[:, column]
        # Same normalization as the rope's: (1/N) sum v_j^2 = 1, positive at the free end.
        v = v * math.sqrt(count / float(np.sum(v * v)))
        shapes.append(v if v[-1] > 0 else -v)
    return omega, shapes


def compare(count, modes=MODES, g=G, length=LENGTH, mass=MASS):
    """One row of the study: errors of the N = count chain against both ropes."""
    omega, shapes = chain_level(count, modes, g, length, mass)
    found = len(omega)
    nodes = np.arange(1, count + 1) * length / count
    longer = length * (1 + 1 / (2 * count))
    rope = frequencies_np(found, length, g)
    rope_longer = frequencies_np(found, longer, g)
    psi = normalized_modes_np(found, nodes, length)
    # The longer rope's modes, normalized over [0, L(1 + 1/(2N))] to the chain's sum.
    psi_longer = normalized_modes_np(found, nodes, longer) * math.sqrt(length / longer)
    return {
        "N": count,
        "omega": omega,
        "freq_error": omega / rope - 1,
        "freq_error_longer": omega / rope_longer - 1,
        "shape_error": np.array([np.max(np.abs(shapes[k] - psi[k])) for k in range(found)]),
        "shape_error_longer": np.array(
            [np.max(np.abs(shapes[k] - psi_longer[k])) for k in range(found)]
        ),
    }


def study(start=1, max_count=1024, modes=MODES):
    rows = []
    count = start
    while count <= max_count:
        rows.append(compare(count, modes))
        count *= 2
    return rows


def observed_orders(rows, key, k):
    """log2(e(N/2) / e(N)) for consecutive rows where mode k exists in both."""
    orders = [None]
    for previous, current in itertools.pairwise(rows):
        if len(previous[key]) > k and len(current[key]) > k:
            ratio = abs(previous[key][k]) / abs(current[key][k])
            orders.append(math.log2(ratio))
        else:
            orders.append(None)
    return orders


def theta_cross_check(max_count=256):
    """Largest relative gap between the x-form and the angle form of the same eigenproblem."""
    worst = 0.0
    count = 1
    while count <= max_count:
        masses, lengths = uniform_chain(MASS, LENGTH, count)
        omega_x, _ = normal_modes(masses, lengths, G, MODES)
        omega_t = normal_frequencies_theta(masses, lengths, G, MODES)
        worst = max(worst, float(np.max(np.abs(omega_t / omega_x - 1))))
        count *= 2
    return worst


def _fmt(value, digits=3):
    return "" if value is None else f"{value:.{digits}e}"


def _order(value):
    return "" if value is None else f"{value:.3f}"


def render(rows, rows_three):
    zeros = jn_zeros(0, MODES)
    out = []
    out.append("# Discrete pendulum against the hanging rope: convergence\n")
    out.append(
        "Generated by `convergence.py` (run it from `physics/oracle`: "
        "`uv run --no-sync python limits/convergence.py`). Do not edit by hand.\n"
    )
    out.append(
        "Chain: N equal masses M/N on rods of length L/N (the paper's section-5 system), "
        "linearized from the Lagrangian, solved as the generalized symmetric eigenproblem "
        "K v = omega^2 M v (`scipy.linalg.eigh`). Rope: omega_k = (j_{0,k}/2) sqrt(g/L), "
        "Psi_k(y) = J0(j_{0,k} sqrt(1 - y/L)) (`rope.py`). N doubles as in the paper, "
        f"n_p = n 2^p, from n = 1 to N = 1024. g = {G}, L = {LENGTH}, M = {MASS}; every number "
        "below is a dimensionless ratio, so the values of g, L, M do not matter.\n"
    )
    out.append(
        "Errors: frequency, omega_k(N)/omega_k - 1; shape, max over the masses of "
        "|v_j - Psi_k(y_j)| with y_j = jL/N, both normalized to (1/N) sum v_j^2 = "
        "(1/L) int Psi^2 dy = 1 and positive at the free end. Order: log2 of the error ratio "
        "between N/2 and N.\n"
    )

    out.append("\n## Frequencies against the rope of length L (the paper's limit)\n")
    header = "| N |"
    rule = "|---:|"
    for k in range(MODES):
        header += f" err omega_{k + 1} | order | N*err |"
        rule += "---:|---:|---:|"
    out.append(header)
    out.append(rule)
    orders = [observed_orders(rows, "freq_error", k) for k in range(MODES)]
    for index, row in enumerate(rows):
        line = f"| {row['N']} |"
        for k in range(MODES):
            if k < len(row["freq_error"]):
                err = row["freq_error"][k]
                line += f" {_fmt(err)} | {_order(orders[k][index])} | {err * row['N']:.5f} |"
            else:
                line += " | | |"
        out.append(line)
    out.append(
        "\nN*err tends to -1/4 for each fixed mode: omega_k(N) = omega_k (1 - 1/(4N) + O(N^-2)), "
        "first order. The modes tabulated here are slower than the rope's. That is not true of "
        "every mode at a given N: the O(N^-2) term grows with the square of the mode number, and "
        "the modes above about 1.6 sqrt(N) are faster than the rope's.\n"
    )

    out.append("\n## Frequencies against the rope of length L(1 + 1/(2N))\n")
    header = "| N |"
    rule = "|---:|"
    for k in range(MODES):
        header += f" err omega_{k + 1} | order | N^2*err |"
        rule += "---:|---:|---:|"
    out.append(header)
    out.append(rule)
    orders = [observed_orders(rows, "freq_error_longer", k) for k in range(MODES)]
    for index, row in enumerate(rows):
        line = f"| {row['N']} |"
        for k in range(MODES):
            if k < len(row["freq_error_longer"]):
                err = row["freq_error_longer"][k]
                line += f" {_fmt(err)} | {_order(orders[k][index])} | {err * row['N'] ** 2:.5f} |"
            else:
                line += " | | |"
        out.append(line)
    limits = ", ".join(f"{(z * z - 2) / 96:.5f}" for z in zeros)
    out.append(
        "\nSecond order. N^2*err approaches (j_{0,k}^2 - 2)/96 = "
        f"{limits} for k = 1..{MODES} (observed; the gap halves with each doubling). That is "
        "the constant of Tricomi's asymptotic expansion of the small zeros of the Laguerre "
        "polynomial L_N, as expected: for equal masses the chain's omega^2 l/g are exactly "
        "those zeros (checked in the tests).\n"
    )

    out.append("\n## Mode shapes\n")
    header = "| N |"
    rule = "|---:|"
    for k in range(MODES):
        header += f" shape err {k + 1} | order |"
        rule += "---:|---:|"
    for k in range(MODES):
        header += f" vs L(1+1/2N), {k + 1} | order |"
        rule += "---:|---:|"
    out.append(header)
    out.append(rule)
    orders = [observed_orders(rows, "shape_error", k) for k in range(MODES)]
    orders_longer = [observed_orders(rows, "shape_error_longer", k) for k in range(MODES)]
    for index, row in enumerate(rows):
        line = f"| {row['N']} |"
        for key, ords in (("shape_error", orders), ("shape_error_longer", orders_longer)):
            for k in range(MODES):
                if k < len(row[key]):
                    line += f" {_fmt(row[key][k])} | {_order(ords[k][index])} |"
                else:
                    line += " | |"
        out.append(line)
    out.append(
        "\nThe shapes converge at first order to the rope's of length L and at second order to "
        "those of the rope of length L(1 + 1/(2N)), like the frequencies.\n"
    )

    out.append("\n## A second doubling sequence, n = 3\n")
    out.append("| N | err omega_1 | order | N*err | shape err 1 | order |")
    out.append("|---:|---:|---:|---:|---:|---:|")
    freq_orders = observed_orders(rows_three, "freq_error", 0)
    shape_orders = observed_orders(rows_three, "shape_error", 0)
    for index, row in enumerate(rows_three):
        err = row["freq_error"][0]
        out.append(
            f"| {row['N']} | {_fmt(err)} | {_order(freq_orders[index])} | "
            f"{err * row['N']:.5f} | {_fmt(row['shape_error'][0])} | "
            f"{_order(shape_orders[index])} |"
        )

    out.append("\n## Cross-check\n")
    out.append(
        "The same eigenproblem in the angles (dense kinetic matrix, `normal_frequencies_theta`) "
        f"agrees with the displacement form to a relative {theta_cross_check():.1e} "
        "for N = 1..256.\n"
    )
    return "\n".join(out) + "\n"


def main():
    rows = study(1, 1024)
    rows_three = study(3, 768)
    target = Path(__file__).with_name("convergence.md")
    target.write_text(render(rows, rows_three))
    print(f"wrote {target}")


if __name__ == "__main__":
    main()
